    /** "R3X" for any Russian callsign (R…, UA–UI…), or null. Kaliningrad is RA2/UA2–UI2 with F or K. */
    fun block(call: String): String? {
        val c = call.uppercase().substringBefore('/').trim()
        val m = Regex("^(R[A-Z]?|U[A-I])(\\d)([A-Z])").find(c) ?: return null
        return "R" + m.groupValues[2] + m.groupValues[3]
    }

    /** The region of a Russian callsign, or null when it is not Russian or not in the table. */
    fun of(call: String): Region? {
        val c = call.uppercase().substringBefore('/').trim()
        val m = Regex("^(R[A-Z]?|U[A-I])(\\d)([A-Z])").find(c) ?: return null
        val digit = m.groupValues[2]; val letter = m.groupValues[3]
        if (digit == "2" && (letter == "F" || letter == "K")) return ALL.firstOrNull { it.rda == "KA" }
        val b = "R$digit$letter"
        return ALL.firstOrNull { b in it.blocks }
    }
